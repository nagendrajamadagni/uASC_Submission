#!/bin/bash
#
# Rebuilds openssl-3.5.0/libcrypto.a to match the archive this artifact's
# measurements were taken against, and installs it where find_target_addr.py
# expects it.
#
# You only need this if openssl-3.5.0/libcrypto.a is missing. It ships with the
# artifact as a prebuilt 27 MB archive -- but it is excluded by the `*.a` rule
# in .gitignore, so a copy obtained through git will not have it.
#
# ---------------------------------------------------------------------------
# WHY THE TOOLCHAIN MATTERS
#
# attacker.nasm hard-codes offsets *within* libcrypto functions and mirrors
# adjacent functions with fixed padding. find_target_addr.py re-derives every
# absolute address automatically, but not those internal ones -- so an archive
# whose functions are laid out differently fails the chain check even though it
# is the same OpenSSL version. Optimisation level and compiler both move them.
#
# The required toolchain was recovered by compiling individual sources and
# diffing per-function symbol sizes against the members of the shipped archive:
#
#   clang-14 -O1 -g   reproduces obj_dat.c, bn_lib.c, aes_core.c, p5_crpt2.c
#                     exactly (every function identical in size)
#   gcc-12   -O0 -g   reproduces none of them
#   clang-14 -O0 -g   reproduces none of them
#
# BEWARE the `compiler:` string inside the shipped archive. It reads
#
#   compiler: gcc -fPIC -pthread -m64 -O0 -g -DOPENSSL_AES_CONST_TIME ...
#
# and it is MISLEADING: that string comes from crypto/buildinf.h, which records
# the *configured* $(CC) $(LIB_CFLAGS) and was evidently generated by a
# different configure pass than the one that compiled the objects. Building
# gcc/-O0 to match it produces an archive that passes a string comparison and
# then fails the chain check. The layout check below is the one that counts.
#
# Byte-identical reproduction is impossible in any case: buildinf.h stamps the
# build date into the archive and `ar` records member mtimes and uid/gid. The
# goal is an archive with the same internal layout, not the same md5.
#
# DO NOT RUN THIS WHILE A MEASUREMENT IS IN PROGRESS. It compiles OpenSSL on
# every core and will wreck the timings of any attack run on this machine.
# ---------------------------------------------------------------------------

set -euo pipefail

VERSION="3.5.0"
SRCDIR="openssl-${VERSION}"
TARBALL="openssl-${VERSION}.tar.gz"
BUILDROOT="$(cd "$(dirname "$0")" && pwd)/openssl-build"
DESTDIR="$(cd "$(dirname "$0")" && pwd)/openssl-${VERSION}"
DEST="${DESTDIR}/libcrypto.a"

CC_WANT="clang-14"
CFLAGS_WANT="-O1 -g -DOPENSSL_AES_CONST_TIME"

# Layout fingerprint: the gap between two adjacent libcrypto functions that
# attacker.nasm mirrors with fixed padding. This is the authoritative check.
WANT_CHAIN_DELTA="0x130"
WANT_PLATFORM="platform: linux-x86_64"

URLS=(
  "https://github.com/openssl/openssl/releases/download/openssl-${VERSION}/${TARBALL}"
  "https://www.openssl.org/source/${TARBALL}"
)

cd "$(dirname "$0")"

echo "=== OpenSSL ${VERSION} -> ${DEST} ==="
echo "    toolchain: ${CC_WANT} ${CFLAGS_WANT}"
echo

if [ -f "$DEST" ]; then
    echo "libcrypto.a is already present:"
    ls -lh "$DEST" | sed 's/^/  /'
    echo
    read -r -p "Rebuild and replace it? [y/N] " reply
    case "$reply" in
        [yY]*) ;;
        *) echo "Nothing to do."; exit 0 ;;
    esac
    cp -v "$DEST" "${DEST}.bak"
    echo
fi

for t in curl tar make perl nm "$CC_WANT"; do
    command -v "$t" >/dev/null 2>&1 || {
        echo "ERROR: '$t' is required but not installed." >&2
        [ "$t" = "$CC_WANT" ] && echo "       On Ubuntu 22.04: sudo apt install clang-14" >&2
        exit 1; }
done

mkdir -p "$BUILDROOT"
cd "$BUILDROOT"

# --- 1. download -----------------------------------------------------------
if [ -f "$TARBALL" ]; then
    echo "--- Archive already downloaded, skipping ---"
else
    echo "--- Downloading ${TARBALL} ---"
    ok=0
    for url in "${URLS[@]}"; do
        echo "  trying $url"
        if curl -fL --retry 3 -o "${TARBALL}.part" "$url"; then
            mv "${TARBALL}.part" "$TARBALL"; ok=1; break
        fi
        echo "  failed, trying next mirror"
    done
    [ "$ok" -eq 1 ] || { echo "ERROR: could not download ${TARBALL}." >&2; exit 1; }
fi

# --- 2. extract ------------------------------------------------------------
echo
echo "--- Extracting (fresh tree) ---"
rm -rf "$SRCDIR"
tar -xf "$TARBALL"
cd "$SRCDIR"

# --- 3. configure ----------------------------------------------------------
echo
echo "--- Configuring ---"
echo "    ./Configure linux-x86_64 no-asm CC=${CC_WANT} CFLAGS=\"${CFLAGS_WANT}\""
./Configure linux-x86_64 no-asm CC="$CC_WANT" CFLAGS="$CFLAGS_WANT"

# --- 4. build --------------------------------------------------------------
# Generate the public headers FIRST, serially. 28 of include/openssl/*.h are
# produced from .h.in templates, and a parallel `make libcrypto.a` races past
# them -- at which point #include <openssl/ui.h> silently resolves against
# /usr/include/openssl instead of this tree, and the build dies deep in
# crypto/asn1 with "unknown type name OSSL_i2d_of_void_ctx".
echo
echo "--- Generating headers ---"
make build_generated

echo
echo "--- Building libcrypto.a on $(nproc) cores (several minutes) ---"
make -j"$(nproc)" libcrypto.a

[ -f libcrypto.a ] || { echo "ERROR: build finished but libcrypto.a is missing." >&2; exit 1; }

# --- 5. verify -------------------------------------------------------------
echo
echo "--- Verifying ---"
fail=0

# NB: capture once and match with a here-string. Piping into `grep -q` under
# `set -o pipefail` reports FAILURE on success -- grep exits at the first
# match, strings takes SIGPIPE, and pipefail propagates its status.
archive_strings=$(strings libcrypto.a)
if grep -qxF "$WANT_PLATFORM" <<< "$archive_strings"; then
    echo "  [OK]   $WANT_PLATFORM"
else
    echo "  [BAD]  expected $WANT_PLATFORM"
    fail=1
fi

delta=$(python3 -c "
import subprocess
out=subprocess.run(['nm','--defined-only','libcrypto.a'],capture_output=True,text=True).stdout
d={}
for ln in out.splitlines():
    p=ln.split()
    if len(p)==3 and p[2] in ('OBJ_nid2obj','OBJ_nid2sn'): d[p[2]]=int(p[0],16)
print(hex(d['OBJ_nid2sn']-d['OBJ_nid2obj']) if len(d)==2 else 'n/a')
" 2>/dev/null || echo "n/a")
if [ "$delta" = "$WANT_CHAIN_DELTA" ]; then
    echo "  [OK]   layout: OBJ_nid2sn - OBJ_nid2obj = $delta"
else
    echo "  [BAD]  layout: OBJ_nid2sn - OBJ_nid2obj = $delta (want $WANT_CHAIN_DELTA)"
    echo "         This archive will NOT satisfy attacker.nasm's fixed padding."
    echo "         Compiler in use: $($CC_WANT --version | head -1)"
    fail=1
fi

if [ "$fail" -ne 0 ]; then
    echo
    echo "ERROR: the archive does NOT match the shipped one; NOT installing." >&2
    echo "It is left at $(pwd)/libcrypto.a" >&2
    exit 1
fi

# --- 6. install ------------------------------------------------------------
echo
echo "--- Installing ---"
mkdir -p "$DESTDIR"
cp -v libcrypto.a "$DEST"

echo
echo "=== Done ==="
ls -lh "$DEST" | sed 's/^/  /'
echo
echo "Now confirm the offsets baked into attacker.nasm still match:"
echo
echo "    ./find_target_addr.py --verify_only"
echo
echo "Expect '[OK]  All 13 chain offsets match attacker.nasm'."
echo
echo "The build tree is ${BUILDROOT} (~2 GB). Remove it with:"
echo
echo "    rm -rf ${BUILDROOT}"
